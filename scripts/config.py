def validate_config():
    """Verify all critical paths and settings exist."""
    errors = []
    
    # Check directories exist or can be created
    for dir_path in [FONTS_DIR, PHOTOS_DIR, TEMPLATES_DIR, OUTPUT_DIR]:
        if not dir_path.exists():
            try:
                dir_path.mkdir(parents=True, exist_ok=True)
            except Exception as e:
                errors.append(f"Cannot create {dir_path}: {e}")
    
    # Warn if critical files missing
    if not HEADSHOT_PATH.exists():
        errors.append(f"Headshot not found: {HEADSHOT_PATH}")
    
    if not README_TEMPLATE_PATH.exists():
        errors.append(f"README template not found: {README_TEMPLATE_PATH}")
    
    # Check GitHub API endpoint
    if not GITHUB_API_ENDPOINT.startswith('https://'):
        errors.append(f"Invalid API endpoint: {GITHUB_API_ENDPOINT}")
    
    return errors

