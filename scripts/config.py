def get_char_for_brightness(brightness: float) -> str:
    """
    Map a brightness value (0.0-1.0) to the ASCII ramp character.
    
    Args:
        brightness: 0.0 (white/bright) to 1.0 (black/dark)
    
    Returns:
        Character from ASCII_RAMP matching brightness level
    """
    if not 0.0 <= brightness <= 1.0:
        raise ValueError(f"Brightness must be 0.0-1.0, got {brightness}")
    
    # Map to index in ramp (0-12)
    index = int(brightness * (len(ASCII_RAMP) - 1))
    return ASCII_RAMP[index]

def load_font_base64(font_path: Path) -> str:
    """Load a WOFF2 font file and return as base64 data URI."""
    import base64
    
    if not font_path.exists():
        raise FileNotFoundError(f"Font file not found: {font_path}")
    
    with open(font_path, 'rb') as f:
        font_bytes = f.read()
    
    b64 = base64.b64encode(font_bytes).decode('ascii')
    return f"data:font/woff2;base64,{b64}"

